import { useEffect, useState } from 'react'
import { восстановитьСессию, выйти } from './api'
import type { Пользователь } from './api'
import Вход from './Vhod'
import Профиль from './Profil'
import './App.css'

export default function App() {
  const [кто, установитьКто] = useState<Пользователь | null>(null)
  const [проверяем, установитьПроверяем] = useState(true)

  // После перезагрузки страницы пропуск (access) теряется — он лежал в памяти
  // вкладки. Но кука refresh_token живёт 7 дней, поэтому просто спрашиваем
  // профиль: запрос получит 401, сам сходит за новым пропуском по куке и
  // повторится. Не вышло — значит мы и правда аноним, показываем форму входа.
  // Если в прошлый раз нажали «Выйти», восстановитьСессию даже не спросит
  // сервер: его кука переживает выход, и без метки мы бы вернулись внутрь.
  useEffect(() => {
    восстановитьСессию()
      .then(установитьКто)
      .finally(() => установитьПроверяем(false))
  }, [])

  const выход = async () => {
    try {
      await выйти()
    } finally {
      установитьКто(null)
    }
  }

  return (
    <div className="страница">
      <header>
        <h1>Рок-группа</h1>
        <p className="слоган">Личный кабинет музыканта</p>
      </header>

      <main>
        {проверяем ? (
          <p className="ждём">Проверяем, вошли ли вы…</p>
        ) : кто ? (
          <Профиль кто={кто} приОбновлении={установитьКто} приВыходе={выход} />
        ) : (
          <Вход приВходе={установитьКто} />
        )}
      </main>

      <footer>
        <p>Шабданова Айша · группа WIN-1-25 · Веб-технологии, ДЗ9 (вход по JWT)</p>
      </footer>
    </div>
  )
}
